-- Схема для Neon (PostgreSQL). Выполнить один раз в SQL Editor.
-- Повторяет таблицы Users, GameHistory, GlobalChat из SQLQ.sql / create_users_table.sql.

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  elo INTEGER NOT NULL DEFAULT 800,
  energy INTEGER NOT NULL DEFAULT 5,
  role VARCHAR(20) NOT NULL DEFAULT 'user',
  is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
  is_premium BOOLEAN NOT NULL DEFAULT FALSE,
  league VARCHAR(50) NOT NULL DEFAULT 'Bronze',
  last_energy_update TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS gamehistory (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userid INTEGER NOT NULL REFERENCES users(id),
  result VARCHAR(50),
  fen TEXT,
  moves TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS globalchat (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userid INTEGER NOT NULL REFERENCES users(id),
  username VARCHAR(50),
  message VARCHAR(500),
  sentat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_users_elo ON users(elo DESC);
CREATE INDEX IF NOT EXISTS idx_globalchat_sentat ON globalchat(sentat DESC);

